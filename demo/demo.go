// Package demo fabricates alerts so every threat mode can be previewed
// without waiting for real weather. Demo alerts are clearly labelled.
package demo

import (
	"fmt"
	"time"

	"github.com/j4mes/ttywx/api"
	"github.com/j4mes/ttywx/modes"
)

type sample struct {
	event, severity, urgency, headline, instruction string
}

var samples = map[modes.Mode]sample{
	modes.Warning: {
		"Wind Advisory", "Moderate", "Expected",
		"Wind Advisory until 6 PM PDT this evening",
		"Winds this strong can make driving difficult, especially for high profile vehicles. Secure outdoor objects.",
	},
	modes.Heightened: {
		"Red Flag Warning", "Severe", "Expected",
		"Red Flag Warning in effect until 8 PM PDT Sunday",
		"A Red Flag Warning means that critical fire weather conditions are either occurring now or will shortly. Avoid any activity that could start a fire.",
	},
	modes.TakeCover: {
		"Tornado Warning", "Extreme", "Immediate",
		"Tornado Warning until 2:45 PM PDT",
		"TAKE COVER NOW! Move to a basement or an interior room on the lowest floor of a sturdy building. Avoid windows.",
	},
}

// Alert returns a fake alert that classifies as mode m for the named
// location (nil for Normal).
func Alert(m modes.Mode, location string, now time.Time) []api.Alert {
	s, ok := samples[m]
	if !ok {
		return nil
	}
	return []api.Alert{{
		ID:          fmt.Sprintf("demo:%s:%s", location, s.event),
		AreaDesc:    location + " (demo)",
		Sent:        now,
		Effective:   now,
		Onset:       now,
		Expires:     now.Add(3 * time.Hour),
		Ends:        now.Add(3 * time.Hour),
		Status:      "Actual",
		MessageType: "Alert",
		Category:    "Met",
		Severity:    s.severity,
		Certainty:   "Observed",
		Urgency:     s.urgency,
		Event:       s.event,
		SenderName:  "ttywx demo",
		Headline:    "[DEMO] " + s.headline,
		Description: "This is a simulated alert generated by ttywx --demo. It is not real.\n\n" +
			"* WHAT...Simulated " + s.event + ".\n\n* WHERE..." + location + ".",
		Instruction: s.instruction,
		Response:    "Execute",
	}}
}

// Initial is the starting demo layout, keyed by location index: a spread of
// modes across the surrounding areas. Nothing starts in TAKE COVER
// so the banner (and bell) only appear when you cycle into it.
func Initial(n int) map[int]modes.Mode {
	m := map[int]modes.Mode{}
	spread := []modes.Mode{modes.Warning, modes.Heightened, modes.Normal, modes.Warning}
	for i := 1; i < n; i++ {
		m[i] = spread[(i-1)%len(spread)]
	}
	return m
}
